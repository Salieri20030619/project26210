manifest=json.loads((w/'qc/SOURCE_MANIFEST.json').read_text())
checks=[]
def ck(name,v):
 checks.append({'check':name,'pass':bool(v)})
 if not v:raise AssertionError(name)
ck('source_snapshot_hashes',all(hashlib.sha256((w/x['snapshot']).read_bytes()).hexdigest()==x['sha256']for x in manifest if 'snapshot'in x))
ck('source_original_hashes',all(any(Path(p).exists() and hashlib.sha256(Path(p).read_bytes()).hexdigest()==x['sha256']for p in x['sources'])for x in manifest))
ck('five_cohorts_75_libraries_40_patients',len(e['cohorts'])==5 and sum(x['libraries']for x in e['cohorts'])==75 and sum(x['patients']for x in e['cohorts'])==40)
ck('11950_malignant_26_patients',sum(x['malignant_cells']for x in e['cohorts'])==11950 and sum(x['malignant_patients']for x in e['cohorts'])==26)
ck('CNV_partition_38670',sum(int(x['n_cells'])for x in e['cnv_counts'])==38670)
ck('258120_cells',sum(int(x['n_cells'])for x in e['celltypes'])==258120)
ck('DE_counts_760_233_527',e['de_counts']=={'tested':15308,'significant':760,'up':233,'down':527})
ck('ORA_17_up_0_down',sum(x['direction']=='up' and float(x['FDR'])<.05 for x in e['ora'])==17 and sum(x['direction']=='down' and float(x['FDR'])<.05 for x in e['ora'])==0)
ck('six_regulon_FDR_associations',len(e['reg_cont'])==6 and all(float(x['BH_FDR'])<.05 and float(x['median_patient_effect'])>0 for x in e['reg_cont']))
ck('four_targets_two_models',len([x for x in e['tymp_activity']if x['type']=='metaVIPER_activity'])==8)
ck('all_39_terminal_endpoints',len(e['terminal_enzyme'])==39)
ck('all_terminal_FDR_nonsignificant',all(float(x['FDR'])>=.05 for x in e['terminal_enzyme']))
ck('all_four_nominal_terminal_endpoints',sum(float(x['P'])<.05 for x in e['terminal_enzyme'])==4)
ck('all_48_trajectory_endpoints',len(e['trajectory'])==48)
ck('all_24_functional_axis_endpoints',len(e['axis'])==24)
ck('all_12_enzyme_F1_endpoints',len(e['enzyme_f1'])==12)
tables=[x for x in m if x['type']=='table']
ck('25_report_tables',len(tables)==25)
ck('all_39_terminal_rows_in_appendix',sum(len(x['rows'])for x in tables if x['caption'].startswith('附表 S8'))==39)
ck('all_48_trajectory_rows_in_appendix',sum(len(x['rows'])for x in tables if x['caption'].startswith('附表 S6'))==48)
ck('all_24_axis_rows_in_appendix',sum(len(x['rows'])for x in tables if x['caption'].startswith('附表 S9'))==24)
ck('all_21_original_terminal_rows',sum(len(x['rows'])for x in tables if x['caption'].startswith('附表 S7'))==21)
ck('all_15_activity_F1_rows',sum(len(x['rows'])for x in tables if x['caption'].startswith('附表 S3'))==15)
headings=[x['text'].split()[0]for x in m if x['type']=='h2' and x['text'].startswith('2.')]
ck('six_result_sections_no_2_3',headings==['2.1','2.2','2.4','2.5','2.6','2.7'])
body='\n'.join(x.get('text','')for x in m)
ck('key_negative_directions_in_text',all(x in body for x in ['-0.03326','-0.64833','-0.68922','-0.22654','-0.20357']))
ck('no_MTA_44fold_claim','44倍'not in body and '44-fold'not in body)
ck('wetlab_directions_kept','Thymidine 升高' in body and 'Spermidine 下降' in body)
p=json.loads((w/'qc/PDF_VALIDATION.json').read_text())
ck('PDF_17pages_zero_images',p['page_count']==17 and p['image_count']==0)
ck('PDF_bounds_clean',all(x['out_of_page_safety_bounds']==0 for x in p['bounds']))
ck('PDF_matches_reviewed_delivery',hashlib.sha256((w/'report/26210_TYMP_report_no_figures_v1.pdf').read_bytes()).hexdigest()==p['sha256'])
ck('glyphs_and_notation_checked',p['negative_effects_visible'] and p['scientific_notation_visible'] and p['no_replacement_character'])
(w/'qc/CONTENT_VALIDATION.json').write_text(json.dumps({'status':'PASS','checks':checks},ensure_ascii=False,indent=2))
