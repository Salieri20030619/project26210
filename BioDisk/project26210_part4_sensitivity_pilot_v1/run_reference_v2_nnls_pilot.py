def gate(stage: str, rows: list[dict[str, object]]) -> None:
    result = subprocess.run([str(MEMORY_GATE)], capture_output=True, text=True, check=False)
    line = (result.stdout or result.stderr).strip()
    rows.append({"stage": stage, "exit_code": result.returncode, "output": line})
    if result.returncode != 0:
        raise RuntimeError(f"Memory gate failed at {stage}: {line}")


def clean_old_abundance(adata: ad.AnnData) -> pd.DataFrame:
    abundance = adata.obsm["q05_cell_abundance_w_sf"]
    if not isinstance(abundance, pd.DataFrame):
        names = adata.uns.get("mod", {}).get("factor_names")
        abundance = pd.DataFrame(abundance, index=adata.obs_names, columns=names)
    abundance = abundance.copy()
    columns = []
    for column in abundance.columns:
        value = str(column)
        for prefix in ABUNDANCE_PREFIXES:
            value = value.replace(prefix, "")
        columns.append(value)
    abundance.columns = columns
    abundance = abundance.div(abundance.sum(axis=1).replace(0, np.nan), axis=0).fillna(0)
    return abundance


def rank_percentile(values: np.ndarray) -> np.ndarray:
    return pd.Series(values).rank(method="average", pct=True).to_numpy(dtype=float)


def hotspot_jaccard(x: np.ndarray, y: np.ndarray, q: float) -> float:
    # Select an exact, equal-sized top-k set. Quantile thresholds are biased by
    # the many tied zero values generated by a sparse NNLS solution.
    n = len(x)
    k = max(1, int(round((1 - q) * n)))
    x_hot = np.zeros(n, dtype=bool)
    y_hot = np.zeros(n, dtype=bool)
    x_hot[np.argsort(x, kind="stable")[-k:]] = True
    y_hot[np.argsort(y, kind="stable")[-k:]] = True
    union = np.count_nonzero(x_hot | y_hot)
    return float(np.count_nonzero(x_hot & y_hot) / union) if union else math.nan


def block_rho(x: np.ndarray, y: np.ndarray, coords: np.ndarray, grid: int = 5) -> float:
    bins = []
    for axis in range(2):
        ranks = pd.Series(coords[:, axis]).rank(method="first")
        bins.append(pd.qcut(ranks, q=grid, labels=False).to_numpy())
    labels = bins[0] * grid + bins[1]
    frame = pd.DataFrame({"block": labels, "x": x, "y": y})
    # Mean is intentional here: block medians collapse sparse NNLS states to
    # zero even when a spatially restricted positive signal is present.
    frame = frame.groupby("block", observed=True).mean(numeric_only=True)
    if frame["x"].nunique() < 2 or frame["y"].nunique() < 2:
        return math.nan
    return float(spearmanr(frame["x"], frame["y"]).statistic)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    reference = pd.read_csv(REF, sep="\t", index_col=0)
    if reference.shape[1] != 14 or reference.index.has_duplicates or reference.columns.has_duplicates:
        raise RuntimeError(f"Unexpected reference shape or identifiers: {reference.shape}")
    memory_rows: list[dict[str, object]] = []
    concordance_rows: list[dict[str, object]] = []
    relation_rows: list[dict[str, object]] = []
    preflight_rows: list[dict[str, object]] = []
    spot_rows: list[pd.DataFrame] = []
    plot_data: dict[str, dict[str, object]] = {}

    for sample, config in SAMPLES.items():
        gate(f"before_{sample}", memory_rows)
        input_path = Path(config["input"])
        old_path = Path(config["old"])
        adata = ad.read_h5ad(input_path)
        old_adata = ad.read_h5ad(old_path)
        common_spots = adata.obs_names.intersection(old_adata.obs_names)
        if len(common_spots) != adata.n_obs or len(common_spots) != old_adata.n_obs:
            adata = adata[common_spots].copy()
            old_adata = old_adata[common_spots].copy()
        shared = [gene for gene in reference.index if gene in adata.var_names]
        if len(shared) < 800:
            raise RuntimeError(f"{sample}: too few marker genes shared: {len(shared)}")
        x = adata[:, shared].X
        if issparse(x):
            x = x.toarray()
        x = np.asarray(x, dtype=float)
        keep_gene = (x.sum(axis=0) > 0) & (reference.loc[shared].sum(axis=1).to_numpy() > 0)
        shared = np.asarray(shared)[keep_gene].tolist()
        x = x[:, keep_gene]
        s = reference.loc[shared].to_numpy(dtype=float)
        s = s / np.maximum(s.sum(axis=0, keepdims=True), 1e-12)
        y = x / np.maximum(x.sum(axis=1, keepdims=True), 1.0)
        weights = np.zeros((adata.n_obs, reference.shape[1]), dtype=float)
        errors = np.zeros(adata.n_obs, dtype=float)
        for i in range(adata.n_obs):
            coef, residual = nnls(s, y[i], maxiter=500)
            total = coef.sum()
            weights[i] = coef / total if total > 0 else 0
            errors[i] = residual
        new_abundance = pd.DataFrame(weights, index=adata.obs_names, columns=reference.columns)
        old_abundance = clean_old_abundance(old_adata).loc[adata.obs_names]
        coords = np.asarray(adata.obsm["spatial"], dtype=float)

        for new_state, old_state in CROSSWALK.items():
            if new_state not in new_abundance or old_state not in old_abundance:
                continue
            new_values = new_abundance[new_state].to_numpy()
            old_values = old_abundance[old_state].to_numpy()
            rho = (
                float(spearmanr(new_values, old_values).statistic)
                if np.unique(new_values).size >= 2 and np.unique(old_values).size >= 2
                else math.nan
            )
            concordance_rows.append({
                "sample": sample,
                "complexity_class": config["class"],
                "new_state": new_state,
                "old_state": old_state,
                "spot_spearman_rho": rho,
                "new_nonzero_spot_fraction": float(np.mean(new_values > 0)),
                "old_nonzero_spot_fraction": float(np.mean(old_values > 0)),
                "q75_hotspot_jaccard": hotspot_jaccard(new_values, old_values, 0.75),
                "q90_hotspot_jaccard": hotspot_jaccard(new_values, old_values, 0.90),
            })

        new_niche = (
            rank_percentile(new_abundance["SPP1-state Macrophage"].to_numpy())
            * rank_percentile(new_abundance["Endothelial"].to_numpy())
            * rank_percentile(new_abundance["SMC/Pericyte"].to_numpy())
        ) ** (1 / 3)
        old_niche = (
            rank_percentile(old_abundance["SPP1+ TAM"].to_numpy())
            * rank_percentile(old_abundance["Endothelial"].to_numpy())
            * rank_percentile(old_abundance["SMC/Pericyte"].to_numpy())
        ) ** (1 / 3)
        new_relation = block_rho(new_abundance["F1-high Malignant"].to_numpy(), new_niche, coords)
        old_relation = block_rho(old_abundance["TYMP-High Malignant"].to_numpy(), old_niche, coords)
        relation_rows.extend([
            {"sample": sample, "route": "old_cell2location", "grid": "5x5", "rho_F1_or_TYMPHigh_vs_SPP1_vascular_niche": old_relation},
            {"sample": sample, "route": "reference_v2_fast_NNLS", "grid": "5x5", "rho_F1_or_TYMPHigh_vs_SPP1_vascular_niche": new_relation},
        ])
        preflight_rows.append({
            "sample": sample,
            "complexity_class": config["class"],
            "n_spots": int(adata.n_obs),
            "n_input_genes": int(adata.n_vars),
            "n_shared_marker_genes": int(len(shared)),
            "median_NNLS_residual": float(np.median(errors)),
            "q95_NNLS_residual": float(np.quantile(errors, 0.95)),
            "weights_sum_median": float(np.median(weights.sum(axis=1))),
        })
        export = new_abundance.copy()
        export.insert(0, "spot", export.index.astype(str))
        export.insert(0, "sample", sample)
        spot_rows.append(export.reset_index(drop=True))
        plot_data[sample] = {
            "coords": coords,
            "old_f1": old_abundance["TYMP-High Malignant"].to_numpy(),
            "new_f1": new_abundance["F1-high Malignant"].to_numpy(),
            "old_spp1": old_abundance["SPP1+ TAM"].to_numpy(),
            "new_spp1": new_abundance["SPP1-state Macrophage"].to_numpy(),
        }

    concordance = pd.DataFrame(concordance_rows)
    relation = pd.DataFrame(relation_rows)
    preflight = pd.DataFrame(preflight_rows)
    concordance.to_csv(OUT / "old_vs_reference_v2_map_concordance_v2.tsv", sep="\t", index=False)
    relation.to_csv(OUT / "key_relation_route_sensitivity_v2.tsv", sep="\t", index=False)
    preflight.to_csv(OUT / "pilot_preflight_qc_v2.tsv", sep="\t", index=False)
    pd.concat(spot_rows, ignore_index=True).to_csv(OUT / "reference_v2_NNLS_spot_fractions_v2.tsv.gz", sep="\t", index=False)
    pd.DataFrame(memory_rows).to_csv(OUT / "memory_gates_v2.tsv", sep="\t", index=False)

    fig, axes = plt.subplots(3, 4, figsize=(13.2, 9.0), constrained_layout=True)
    panels = [
        ("old_f1", "Old TYMP-high"),
        ("new_f1", "Rebuilt F1-high"),
        ("old_spp1", "Old SPP1+ TAM"),
        ("new_spp1", "Rebuilt SPP1 state"),
    ]
    for row, sample in enumerate(SAMPLES):
        data = plot_data[sample]
        coords = data["coords"]
        for col, (key, title) in enumerate(panels):
            values = data[key]
            vmax = float(np.quantile(values, 0.98))
            scatter = axes[row, col].scatter(
                coords[:, 0], -coords[:, 1], c=values, s=4.5, cmap="magma", linewidths=0,
                vmin=0, vmax=max(vmax, 1e-12), rasterized=True,
            )
            axes[row, col].set_aspect("equal")
            axes[row, col].axis("off")
            if row == 0:
                axes[row, col].set_title(title, fontsize=11)
            if col == 0:
                axes[row, col].text(-0.04, 0.5, sample, transform=axes[row, col].transAxes, rotation=90, va="center", ha="right", fontsize=11, fontweight="bold")
            fig.colorbar(scatter, ax=axes[row, col], fraction=0.035, pad=0.01)
    fig.suptitle("Three-sample reference sensitivity pilot (relative abundance)", fontsize=13, fontweight="bold")
    fig.savefig(OUT / "three_sample_old_vs_reference_v2_maps_v2.png", dpi=300, bbox_inches="tight")
    fig.savefig(OUT / "three_sample_old_vs_reference_v2_maps_v2.pdf", bbox_inches="tight")
    plt.close(fig)

    broad_states = ["B cell", "Dendritic cell", "Endothelial", "Mast cell", "Monocyte", "NK cell", "Other Macrophage", "SMC/Pericyte", "T cell"]
    broad = concordance.loc[concordance["new_state"].isin(broad_states)]
    key_direction = relation.pivot(index="sample", columns="route", values="rho_F1_or_TYMPHigh_vs_SPP1_vascular_niche")
    paired_finite = key_direction.notna().all(axis=1)
    same_direction = (
        np.sign(key_direction.loc[paired_finite, "old_cell2location"])
        == np.sign(key_direction.loc[paired_finite, "reference_v2_fast_NNLS"])
    )
    decision = {
        "status": "completed",
        "created_at": datetime.now().astimezone().isoformat(timespec="seconds"),
        "samples": list(SAMPLES),
        "method": "fast NNLS on patient/study-balanced reference-v2 marker signatures",
        "not_formal_cell2location": True,
        "median_broad_state_map_rho": float(broad["spot_spearman_rho"].median()),
        "key_relation_same_direction_samples": int(same_direction.sum()),
        "key_relation_evaluable_samples": int(len(same_direction)),
        "pilot_interpretation": (
            "promising_for_one formal mapping follow-up" if broad["spot_spearman_rho"].median() >= 0.3 and same_direction.sum() >= 2
            else "definition-sensitive; do not start full mapping"
        ),
        "inference_boundary": "NNLS is a rapid sensitivity screen and cannot replace posterior cell2location abundance.",
    }
    (OUT / "pilot_decision_v2.json").write_text(json.dumps(decision, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    manifest_rows = []
    for path in sorted(OUT.iterdir()):
        if path.is_file() and path.name != "file_manifest_v2.tsv":
            manifest_rows.append({"file": path.name, "size_bytes": path.stat().st_size, "sha256": hashlib.sha256(path.read_bytes()).hexdigest()})
    pd.DataFrame(manifest_rows).to_csv(OUT / "file_manifest_v2.tsv", sep="\t", index=False)
    print(json.dumps(decision, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
